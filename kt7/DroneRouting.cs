// ПИСЬМЕННОЕ ОБОСНОВАНИЕ ДЕКОМПОЗИЦИИ
//
// 1. Что такое одно «состояние» поиска.
//    Состояние — пара (станция, остаток заряда сразу после прибытия на неё, уже с учётом
//    дозаправки). На зарядной станции остаток всегда равен ёмкости батареи, поэтому у неё
//    ровно одно состояние; у обычной станции — по одному на каждый возможный остаток.
//    Стартовое состояние — (start, batteryCapacity). Переход по ребру u→v из (u, b) возможен
//    только при b >= BatteryUsage и ведёт в (v, b - BatteryUsage) либо в (v, batteryCapacity),
//    если v зарядная; цена перехода — Cost ребра.
//
// 2. Почему обычная Дейкстра по вершинам даёт неверный результат.
//    Пример — граф «Ловушка» из Program.cs (ёмкость 100, зарядных станций нет):
//        0→1 (стоимость 1, заряд 80)    0→2 (стоимость 2, заряд 10)
//        2→1 (стоимость 2, заряд 10)    1→3 (стоимость 1, заряд 50)
//        0→3 (стоимость 20, заряд 100)
//    На станцию 1 можно прибыть двумя способами: напрямую за 1 с остатком 20 или через
//    станцию 2 за 4 с остатком 80. Перелёт 1→3 требует 50.
//      - Дейкстра вообще без заряда отвечает 2 (0→1→3) — такого маршрута не существует,
//        на втором перелёте заряда 20 < 50.
//      - Дейкстра по вершинам, которая помнит заряд только самого дешёвого пути, фиксирует
//        для станции 1 стоимость 1 с остатком 20. Более дорогое прибытие (4, остаток 80)
//        она отбрасывает как «худшее», перелёт 1→3 оказывается закрыт, и ответ — 20 (0→3).
//      - Правильный ответ — 5 (0→2→1→3): более дорогое прибытие на станцию 1 открывает
//        дешёвое продолжение. Он находится, только если (1, 20) и (1, 80) — разные состояния.
//    Второй пример — граф «Возврат»: чтобы долететь, нужно дважды побывать на станции 1
//    (слетать с неё на зарядку и вернуться). Алгоритм, помечающий станцию пройденной один
//    раз, такой маршрут найти не может в принципе.
//
// 3. Почему словаря «состояние → минимальная стоимость» достаточно.
//    - Всё, что дрон может сделать дальше, определяется только текущей станцией и остатком
//      заряда и не зависит от того, как он сюда попал. Значит, из двух маршрутов, пришедших
//      в ОДНО И ТО ЖЕ состояние, более дорогой никогда не даст лучшего итога: любое его
//      продолжение доступно и более дешёвому. Отбрасывать его безопасно. Маршруты с разным
//      остатком в одной станции попадают в разные ключи словаря и друг друга не вытесняют —
//      именно этим исключена потеря, описанная в пункте 2.
//    - Стоимости перелётов неотрицательны, поэтому стоимость вдоль маршрута не убывает,
//      и состояния извлекаются из очереди в порядке неубывания стоимости. В момент
//      извлечения состояния его стоимость окончательна (обычный довод Дейкстры, применённый
//      к графу состояний). Поэтому первое извлечённое состояние со станцией destination —
//      с каким бы остатком заряда оно ни было — даёт минимум среди всех допустимых
//      маршрутов: все остальные состояния назначения стоят не меньше.
//      При отрицательных стоимостях это рассуждение неверно, метод их не поддерживает.
//    - Состояний конечное число: не больше V * (batteryCapacity + 1), поэтому алгоритм
//      завершается даже при циклах. Если очередь опустела, перебраны все достижимые
//      состояния, и ответ -1 означает, что допустимого маршрута действительно нет.

namespace Kt7;

/// <summary>Перелёт между станциями.</summary>
public record FlightEdge(int To, int Cost, int BatteryUsage);

/// <summary>Состояние поиска: станция и остаток заряда после прибытия (и дозаправки).</summary>
public record State(int Station, int Battery);

/// <summary>Сеть станций: взвешенный список смежности и множество зарядных станций.</summary>
public class Graph
{
    public Dictionary<int, List<FlightEdge>> Adjacency = new();
    public HashSet<int> ChargingStations = new();

    /// <summary>Добавляет направленный перелёт from → to.</summary>
    public void AddEdge(int from, int to, int cost, int batteryUsage)
    {
        if (!Adjacency.TryGetValue(from, out var edges))
            Adjacency[from] = edges = new List<FlightEdge>();

        edges.Add(new FlightEdge(to, cost, batteryUsage));
    }
}

public static class DroneRouting
{
    /// <summary>
    /// Минимальная суммарная стоимость маршрута от start до destination, на каждом перелёте
    /// которого хватает заряда. Алгоритм Дейкстры по состояниям (станция, остаток заряда).
    /// Сложность: O(S log S + E * B), где S — число достижимых состояний, B — число разных
    /// остатков заряда на станции.
    /// </summary>
    /// <returns>Минимальная стоимость или -1, если допустимого маршрута нет.</returns>
    public static int MinCostRoute(Graph graph, int start, int destination, int batteryCapacity)
    {
        var bestCost = new Dictionary<State, int>();
        var pq = new PriorityQueue<State, int>();

        var startState = new State(start, batteryCapacity);
        bestCost[startState] = 0;
        pq.Enqueue(startState, 0);

        while (pq.TryDequeue(out var current, out int currentCost))
        {
            // Устаревшая запись: это состояние уже было улучшено и обработано с меньшей стоимостью.
            if (currentCost > bestCost[current])
                continue;

            if (current.Station == destination)
                return currentCost;

            if (!graph.Adjacency.TryGetValue(current.Station, out var edges))
                continue;

            foreach (var edge in edges)
            {
                if (edge.BatteryUsage > current.Battery)
                    continue; // не хватает заряда на этот перелёт — переход недопустим

                // На зарядной станции остаток при прибытии не важен: батарея восполняется до максимума.
                int remainingBattery = graph.ChargingStations.Contains(edge.To)
                    ? batteryCapacity
                    : current.Battery - edge.BatteryUsage;

                var nextState = new State(edge.To, remainingBattery);
                int newCost = currentCost + edge.Cost;

                if (!bestCost.TryGetValue(nextState, out int known) || newCost < known)
                {
                    bestCost[nextState] = newCost;
                    pq.Enqueue(nextState, newCost);
                }
            }
        }

        return -1; // перебраны все достижимые состояния, destination среди них нет
    }
}
